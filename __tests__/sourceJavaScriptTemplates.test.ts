import {sourceRuleText} from '../src/core/sourceRule';

test('runs metadata template scripts with rule lookup, original input and variables', () => {
  const variables=new Map<string,string>();
  const context={variables,baseUrl:'https://example.org'};
  const data={name:'西游记',updated_at:1704067200};
  expect(sourceRuleText(data,'{{java.getString("$.name")}} {{java.getString("$.updated_at")}}',false,context)).toBe('西游记 1704067200');
  expect(sourceRuleText(data,'{{result.name}}',false,context)).toBe('西游记');
  expect(sourceRuleText(data,'{{java.get("x")}}|{{java.put("x","新")}}',false,context)).toBe('新|新');
  expect(variables.get('x')).toBe('新');
});

test('setContent survives consecutive script stages with their own result values', () => {
  const rule='<js>java.setContent("新内容","https://new.example/");"中间";</js><js>result+"|"+src+"|"+baseUrl</js>';
  expect(sourceRuleText('原文',rule,false,{baseUrl:'https://old.example/'})).toBe('中间|新内容|https://new.example/');
  const query='<js>java.setContent("<p>新文</p>");result;</js><js>java.getString("p@text")</js>';
  expect(sourceRuleText('<p>原文</p>',query)).toBe('新文');
});

test('renders primitive and array values while preserving empty results', () => {
  expect(sourceRuleText('', '{{1+2}}|{{true}}|{{null}}|{{["甲","乙"]}}')).toBe('3|true||甲,乙');
  expect(()=>sourceRuleText('', '{{missingFunction()}}')).toThrow(/JavaScript/);
});

test('runs a 1321 collection timestamp template with native millisecond offsets', () => {
  const rule="{{java.timeFormatUTC(java.getString('$.updated_at')*1000,'yyyy-MM-dd',8)}}";
  expect(sourceRuleText({updated_at:1704067200},rule)).toBe('2024-01-01');
  expect(sourceRuleText({updated_at:1704067200},"{{java.timeFormatUTC(java.getString('$.updated_at')*1000,'yyyy-MM-dd HH:mm:ss',8*60*60*1000)}}")).toBe('2024-01-01 08:00:00');
});

test('formats local and explicit-offset dates and Java quoted literals', () => {
  const {runSourceJavaScript}=require('../src/core/sourceJavaScript');
  const timestamp=1704067200000, local=new Date(timestamp);
  const pad=(n:number)=>String(n).padStart(2,'0');
  expect(runSourceJavaScript('java.timeFormat(result)',timestamp)).toBe(`${local.getFullYear()}/${pad(local.getMonth()+1)}/${pad(local.getDate())} ${pad(local.getHours())}:${pad(local.getMinutes())}`);
  expect(runSourceJavaScript('java.timeFormatUTC(result,"yy/MM/dd \'at\' HH:mm:ss.SSS",-19800000)',timestamp)).toBe('23/12/31 at 18:30:00.000');
  expect(runSourceJavaScript('java.timeFormatUTC(result,"HH:mm:ss.SSS",8)',timestamp)).toBe('00:00:00.008');
});

test('formats Java day-of-year, day-of-week-in-month and fixed offset fields', () => {
  const {runSourceJavaScript}=require('../src/core/sourceJavaScript');
  const format=(time:number,offset:number,pattern='D F Z X XX XXX')=>
    runSourceJavaScript(`java.timeFormatUTC(${time},"${pattern}",${offset})`,'');
  // Expected values are generated by SimpleDateFormat with SimpleTimeZone.
  expect(format(1704067200000,0)).toBe('1 1 +0000 Z Z Z');
  expect(format(1704067200000,19800000)).toBe('1 1 +0530 +05 +0530 +05:30');
  expect(format(1704067200000,-12600000)).toBe('365 5 -0330 -03 -0330 -03:30');
  expect(format(1704067200000,8)).toBe('1 1 +0000 +00 +0000 +00:00');
  expect(format(1704067200000,1234567)).toBe('1 1 +0020 +00 +0020 +00:20');
  expect(format(Date.UTC(2024,1,29),0,'DDD FF')).toBe('060 05');
  expect(format(Date.UTC(2023,11,31),0,'DDD FF')).toBe('365 05');
  expect(()=>format(0,0,'XXXX')).toThrow(/格式无效/);
});

test('substitutes source fields inside JavaScript rules before executing them', () => {
  const data={time:1704067200000,category_name:'玄幻',status:50};
  expect(sourceRuleText(data, '@js:java.timeFormatUTC({{$.time}},"yyyy-MM-dd",0)')).toBe('2024-01-01');
  expect(sourceRuleText(data, '{{$.category_name}},{{$.status}}@js:result.replace(/50/,"完结")')).toBe('玄幻,完结');
  expect(sourceRuleText(data, '<js>java.timeFormatUTC({{$.time}},"yyyy-MM-dd",0)</js>')).toBe('2024-01-01');
  expect(sourceRuleText(data, '{{$.status}}@js:java.getString("$.category_name")+":"+result+":"+{{$.status}}')).toBe('玄幻:50:50');
  expect(sourceRuleText(data, '{{java.put("stage","保留")}}@js:java.get("stage")')).toBe('保留');
});

test('rejects unsupported date patterns and oversized template expansions', () => {
  const {runSourceJavaScript}=require('../src/core/sourceJavaScript');
  expect(()=>runSourceJavaScript('java.timeFormatUTC(0,"MMMM",0)','')).toThrow(/暂不支持/);
  expect(()=>sourceRuleText('', '{{1}}'.repeat(65))).toThrow(/限制/);
});

test('setContent updates later template lookups and bindings in native evaluation order', () => {
  const html='<p>原文</p>';
  const context={baseUrl:'https://old.example/',src:html};
  expect(sourceRuleText(html,'{{java.getString("p@text")}}|{{java.setContent("<p>新文</p>"),""}}',false,context)).toBe('新文|');
  expect(sourceRuleText(html,'{{@@p@text}}|{{java.setContent("<p>新文</p>"),""}}',false,context)).toBe('新文|');
  expect(sourceRuleText(html,'{{baseUrl}}|{{src}}|{{java.setContent("新内容","https://new.example/"),""}}',false,context)).toBe('https://new.example/|新内容|');
  expect(sourceRuleText(html,'{{java.setContent("<p>新文</p>"),""}}@js:java.getString("p@text")',false,context)).toBe('新文');
  expect(sourceRuleText('旧内容','{{result}}|{{src}}|{{java.setContent("新内容"),""}}')).toBe('旧内容|新内容|');
  expect(sourceRuleText('', '{{java.getString("$.v")}}|{{(function(){var o={v:"一"};java.setContent(o);o.v="二";return "";})()}}')).toBe('二|');
  expect(sourceRuleText('', '{{$.v}}|{{java.setContent("{\\"v\\":\\"新\\"}"),""}}')).toBe('新|');
});
